ROOT = Path(__file__).resolve().parents[1]
SYSTEM = '''You are NeatRescue, an incident investigation and code-repair agent.
You are repairing four pure Python tool adapter functions, not selecting a predefined config.
Use only the public contract and observations supplied in this JSON. No external tools exist.
The exact faults are not disclosed. Do not claim a cause without code or probe evidence.
Choose ONE available action per turn, returning the specified JSON schema:
inspect_source: read the faulty Python and actual Entire code graph output.
probe: run a named diagnostic family on the current source and inspect counterexamples.
replay_ledger: execute the synthetic SQLite commit -> lost acknowledgement -> connection restart -> retry sequence, including legitimate sibling requests. No real payments.
challenge_incoming: test an incoming quick-fix suggestion; it may overfit the initial incident.
submit_patch: supply COMPLETE Python source for all four functions. It must obey the pure subset.
test_patch: independent development checks; learn from counterexamples, do not alter the grader.
finish: freeze a development-passing patch; the controller privately tests newly generated cases.
A failed frozen-candidate test ends this incident without release. No production deployment exists.
Do not include reasoning chains; public_summary is a short evidence-based action justification.
The source repair must preserve all public contracts, not just reported examples. Never import
or call external APIs or files. Keep code simple: returns, comparisons, if, locals and min/max.
No loops, imports, recursion, multiplication/power, comprehensions, decorators or annotations.
No docstrings or f-strings; use comments and string concatenation. Source is empty unless submitting a patch.
'''

BASE_SCHEMA = {'type':'object','properties':{
    'action':{'type':'string'},
    'probe':{'type':'string'},
    'source':{'type':'string','maxLength':6000},
    'public_summary':{'type':'string','maxLength':450}},
    'required':['action','probe','source','public_summary'],'additionalProperties':False}


def parse_planner_response(envelope: dict) -> dict:
    if envelope.get('is_error'):
        raise RuntimeError('Planner error: '+str(envelope.get('result',''))[:400])
    value=envelope.get('structured_output')
    if value is None:
        raw=envelope.get('result','').strip()
        if raw.startswith('```'):
            raw='\n'.join(raw.splitlines()[1:-1])
        value=json.loads(raw)
    if not isinstance(value,dict):
        raise ValueError('Planner output must be an object')
    return value


class BlindCase:
    def __init__(self, seed: int, journal: Journal, source_text: str | None = None, incoming_source: str | None = None):
        from . import blindbench as bench
        from .bounded_python import load_validated_source
        # The LIVE path never executes generated Python bytecode in the host.
        self.bench=bench
        self.journal=journal
        incident=bench.make_incident(seed)
        # Whitelist public fields even when the generator returns flat metadata.
        allowed_public=('incident_id','contract','symptom','faulty_source')
        public_raw=incident.get('public',incident)
        self.public={k:public_raw[k] for k in allowed_public}
        private=incident.get('private',{'mutation_ids':incident.get('mutation_ids',[])})
        if source_text is not None:
            bench.validate_source(source_text)
            self.public['faulty_source']=source_text
            self.public['incident_id']='uploaded-'+hashlib.sha256(source_text.encode()).hexdigest()[:12]
            private={'input_origin':'explicitly_supplied_source','mutation_ids':'unknown; not generated by fault bank'}
        self.original=self.public['faulty_source']
        self.current=self.original
        self.incoming_source=incoming_source
        if incoming_source is not None:
            bench.validate_source(incoming_source)
            journal.save('incoming_proposal.json', {'source':incoming_source,
                'origin':'explicit caller-supplied synthetic proposal, not a hidden repair answer'})
        self.ledger_checked=False
        self.inspected=False
        self.challenged=False
        self.probed:set[str]=set()
        self.patch_count=0
        self.tested_hash:str|None=None
        self.development:dict|None=None
        self.finished=False
        self.report:dict|None=None
        self.history:list[dict]=[]
        self.workspace=journal.directory/'target'
        self.workspace.mkdir()
        (self.workspace/'adapter.py').write_text(self.original)
        (self.workspace/'CONTRACT.json').write_text(json.dumps(self.public['contract'],indent=2))
        for cmd in (['git','init','-b','main',str(self.workspace)],
                    ['git','-C',str(self.workspace),'add','adapter.py','CONTRACT.json'],
                    ['git','-C',str(self.workspace),'-c','user.name=NeatRescue','-c','user.email=local@example.invalid','commit','-m','Materialize newly generated incident target']):
            subprocess.run(cmd,check=True,capture_output=True,text=True,timeout=10)
        # This is NOT in the planner working directory; no tools can read it.
        journal.save('sealed_incident.json',{'seed':seed,'private':private,
            'original_source_sha256':hashlib.sha256(self.original.encode()).hexdigest()})
        self.view={k:v for k,v in self.public.items() if k!='faulty_source'}
        journal.save('public_incident.json',self.view)
        journal.save('source_before.json',{'source':self.original})
        baseline=bench.evaluate(self.original,seed=20261010,count=80)
        journal.save('baseline.json',baseline)
        self.baseline=baseline
        self.dev_seed=20261010

    def actions(self) -> list[str]:
        if self.finished:return []
        if (self.journal.directory / 'final_plan.json').exists():
            return ['finish']  # No new patch or final seed after the first freeze.
        if self.patch_count and self.tested_hash!=hashlib.sha256(self.current.encode()).hexdigest():
            return ['test_patch']
        if self.development and self.development['passed']:
            return ['finish']
        result=[]
        if not self.inspected:result.append('inspect_source')
        if not self.challenged:result.append('challenge_incoming')
        if len(self.probed)<2:result.append('probe')
        if self.inspected and not self.ledger_checked:result.append('replay_ledger')
        if self.inspected and self.challenged and self.probed and self.patch_count<3:
            result.append('submit_patch')
        return result

    def planner_view(self) -> dict:
        return {'incident':self.view,'available_actions':self.actions(),
                'remaining_probes':[p for p in self.bench.PROBES if p not in self.probed],
                'progress':{'source_inspected':self.inspected,'incoming_patch_challenged':self.challenged,
                            'completed_probes':sorted(self.probed),'patches':self.patch_count,
                            'ledger_replay_observed':self.ledger_checked},
                'current_source':self.current if self.inspected else 'Use inspect_source',
                'tool_history':self.history[-6:]}

    def execute(self, decision: dict) -> dict:
        action=decision.get('action')
        if action not in self.actions():raise ValueError('Action unavailable: '+str(action))
        if action=='inspect_source':
            cmd=[str(ROOT/'.tools/entire-graph'),'search','--repo',str(self.workspace),
                 '--query','eligibility policy refund cents operation key tenant retry inventory',
                 '--top-k','4','--format','json','--max-context-bytes','5000']
            r=subprocess.run(cmd,check=False,capture_output=True,text=True,timeout=35)
            if r.returncode:raise RuntimeError('Entire graph failed: '+r.stderr[-300:])
            try:graph=json.loads(r.stdout)
            except json.JSONDecodeError:graph={'text':r.stdout[:5000]}
            self.journal.save('entire_blind_target_context.json',{'command':cmd,'result':graph})
            self.inspected=True
            result={'source':self.current,'repository_context_source':'Entire graph','context':graph}
        elif action=='probe':
            probe=decision.get('probe')
            if probe not in self.bench.PROBES or probe in self.probed:raise ValueError('Unknown/repeated probe')
            self.probed.add(probe)
            result=self.bench.evaluate(self.current,seed=self.dev_seed,count=16,probe=probe)
        elif action=='replay_ledger':
            from .ledger_replay import replay
            result=replay(self.current, seed=self.dev_seed)
            self.ledger_checked=True
            self.journal.save('diagnostic_ledger_replay.json', result)
        elif action=='challenge_incoming':
            import ast
            if self.incoming_source is None:
                # Preserve the earlier explicitly declared negative fixture.
                tree=ast.parse(self.original)
                for node in tree.body:
                    if isinstance(node,ast.FunctionDef) and node.name=='eligible':
                        node.body=[ast.Return(value=ast.Constant(value=False))]
                incoming=ast.unparse(ast.fix_missing_locations(tree))+'\n'
                smoke=self.bench.smoke_example(incoming)
                provenance='declared_always_deny_fixture'
            else:
                from .ledger_replay import replay
                incoming=self.incoming_source
                narrow=replay(incoming, seed=self.dev_seed)
                smoke={'passed':narrow['retry_only_passed'],
                    'scope':'Original refund plus its replay only; excludes legitimate sibling and other tenant'}
                provenance='caller_supplied_incomplete_patch_fixture'
            result={'provenance':provenance,'single_incident':smoke,'candidate_source':incoming,
                    'independent_validation':final_gate.evaluate_candidate(incoming,seed=self.dev_seed,count=80)}
            self.journal.save('misleading_patch_challenge.json',{'source':incoming,**result})
            self.challenged=True
        elif action=='submit_patch':
            source=decision.get('source')
            if not isinstance(source,str):raise ValueError('Source must be a string')
            self.bench.validate_source(source)
            if source.strip()==self.current.strip():raise ValueError('No-op patch rejected')
            before=self.current
            self.current=source
            self.patch_count+=1
            self.tested_hash=None
            self.development=None
            (self.workspace/'adapter.py').write_text(source)
            patch=''.join(difflib.unified_diff(before.splitlines(True),source.splitlines(True),
                 fromfile='a/adapter.py',tofile='b/adapter.py'))
            self.journal.save(f'patch_{self.patch_count}.json',{'source':source,'unified_diff':patch,
                'sha256':hashlib.sha256(source.encode()).hexdigest()})
            result={'status':'UNVERIFIED_SOURCE_PATCH','source_sha256':hashlib.sha256(source.encode()).hexdigest(),
                    'diff':patch,'options_selected_from_menu':False}
        elif action=='test_patch':
            identity=final_gate.verifier_identity()
            result=final_gate.evaluate_candidate(self.current,seed=self.dev_seed,count=80)
            if final_gate.verifier_identity()!=identity:
                raise ValueError('Verifier changed during development evaluation')
            self.development=result
            self.tested_hash=hashlib.sha256(self.current.encode()).hexdigest()
            self.journal.save(f'development_{self.patch_count}.json',result)
            self.journal.save(f'development_{self.patch_count}_binding.json',
                final_gate.development_binding(self.journal.directory,self.current,
                    self.patch_count,result,identity))
        else:
            frozen=hashlib.sha256(self.current.encode()).hexdigest()
            if self.tested_hash!=frozen or not self.development or not self.development['passed']:
                raise ValueError('Cannot release unverified source')
            gated=final_gate.finalize(self.journal.directory,self.current,self.patch_count,self.journal)
            fresh_seed=gated['plan']['seed']
            holdout=gated['outcome']['result']
            self.journal.save('sealed_final_validation.json',{'seed':fresh_seed,'result':holdout,
                'plan_sha256':gated['plan']['plan_sha256'],
                'outcome_sha256':gated['outcome']['outcome_sha256']})
            self.finished=True
            self.report={'status':'VALIDATED_SOURCE_PATCH' if holdout['passed'] else 'REJECTED_FINAL_VALIDATION',
                'run_id':self.journal.run_id,'incident_id':self.public['incident_id'],
                'source_sha256':frozen,'baseline':self.baseline,'development':self.development,
                'fresh_generated':holdout,'fresh_seed':fresh_seed,'patch_count':self.patch_count,
                'final_plan_sha256':gated['plan']['plan_sha256'],
                'final_outcome_sha256':gated['outcome']['outcome_sha256'],
                'final_outcome_reused':gated['reused_outcome'],
                'code_repair_not_config_selection':True,'candidate_evaluator':'bounded Python AST subset, not unrestricted CPython','planner_filesystem_tools':False,
                'planner_saw_reference_or_mutation_ids':False,'production_modified':False,
                'claim_boundary':'Synthetic four-function adapter repair, not arbitrary repository or production safety.'}
            self.journal.save('report.json',self.report)
            result=self.report
        self.history.append({'action':action,'result':result})
        return result


def planner_call(public_state: dict, cwd: Path, call_dir: Path) -> dict:
    import copy
    schema=copy.deepcopy(BASE_SCHEMA)
    schema['properties']['action']['enum']=public_state['available_actions']
    cli=Path.home()/'.npm-global/bin/claude'
    prompt='Public incident state. Choose your next tool action.\n'+canonical(public_state)
    cmd=[str(cli),'-p','--model',os.environ.get('NEATRESCUE_PLANNER_MODEL','claude-opus-5'),'--output-format','json','--json-schema',canonical(schema),
         '--tools','','--strict-mcp-config','--mcp-config','{"mcpServers":{}}',
         '--setting-sources','project','--permission-mode','dontAsk','--system-prompt',SYSTEM,
         '--effort','medium','--max-turns','6']
    call_dir.mkdir()
    (call_dir/'public_request.json').write_text(json.dumps(public_state,indent=2))
    started=time.monotonic()
    out=subprocess.run(cmd,input=prompt,cwd=str(cwd),capture_output=True,text=True,timeout=100)
    (call_dir/'stdout.json').write_text(out.stdout)
    (call_dir/'stderr.txt').write_text(out.stderr)
    if out.returncode:raise RuntimeError('Planner process failed: '+str(out.returncode)+' '+out.stderr[-300:])
    envelope=json.loads(out.stdout)
    response=parse_planner_response(envelope)
    return {'decision':response,'duration_s':round(time.monotonic()-started,3),
            'usage':envelope.get('usage'),'model_usage':envelope.get('modelUsage'),
            'session_id':envelope.get('session_id'),'provider_reported_cost_estimate_usd':envelope.get('total_cost_usd'),
            'billing_note':'Provider-reported estimate, not an additional invoice; existing CLI login used.'}


def run(seed: int, max_actions: int=12, source_text: str | None = None, incoming_source: str | None = None) -> dict:
    load_local_environment()
    import neatlogs
    key=os.environ.get('NEATLOGS_API_KEY','').strip()
    if key.startswith('<'):key=''
    neatlogs.init(api_key=key or None,endpoint='https://ingest.neatlogs.com',
                  workflow_name='blind-code-repair',instrumentations=[],disable_export=not bool(key))
    journal=Journal()
    case=BlindCase(seed,journal,source_text,incoming_source)
    journal.save('manifest.json',{'code_hashes':{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in (ROOT/'neatrescue').glob('*.py')}, 'execution_mode':'LIVE_CLAUDE_CODE_PLANNER','model':'default CLI model (actual response metadata recorded)',
        'target':'newly_generated_four_function_tool_adapter','planner_tools':'none; public JSON tools implemented by host only',
        'neatlogs_export':'ENABLED_NOT_CONFIRMED' if key else 'LOCAL_ONLY_MISSING_KEY',
        'fault_selection_hidden_from_planner':True,'final_seed_generated_after_freeze':True})
    started=time.monotonic()
    journal.emit('blind_incident_started',{'incident_id':case.public['incident_id'],'baseline_passes':case.baseline['passes'],
                                        'baseline_total':case.baseline['total']})
    try:
        with neatlogs.trace('blind-code-repair',kind='WORKFLOW'):
            for i in range(max_actions):
                if time.monotonic()-started>650:raise TimeoutError('Incident budget exhausted')
                state=case.planner_view()
                if not state['available_actions']:raise RuntimeError('No safe actions remain')
                wrapped=neatlogs.span(kind='AGENT',name='restricted-claude-planner',capture_input=True,capture_output=True)(planner_call)
                response=wrapped(state,case.workspace,journal.directory/f'call_{i:02d}')
                journal.emit('blind_model_decision',response)
                decision=response['decision']
                try:
                    traced=neatlogs.span(kind='TOOL',tool_name=decision['action'],capture_input=True,capture_output=True)(case.execute)
                    result=traced(decision)
                except (ValueError,KeyError,TypeError,subprocess.TimeoutExpired) as exc:
                    result={'error':type(exc).__name__,'message':str(exc)[:500]}
                    case.history.append({'action':decision.get('action'),'result':result})
                journal.emit('blind_tool_result',{'action':decision.get('action'),'result':result})
                if case.finished:
                    case.report['elapsed_s']=round(time.monotonic()-started,3)
                    case.report['model_decisions']=i+1
                    journal.save('report.json',case.report)
                    journal.emit('terminal',{'status':case.report['status'],'elapsed_s':case.report['elapsed_s']})
                    return case.report
            raise RuntimeError('No validated source patch within action budget')
    except Exception as exc:
        result={'status':'INCOMPLETE','run_id':journal.run_id,'error':type(exc).__name__,'detail':str(exc)[:600],
                'elapsed_s':round(time.monotonic()-started,3),'production_modified':False}
        journal.save('report.json',result);journal.emit('terminal',result);return result
    finally:
        f=neatlogs.flush(timeout_millis=5000);s=neatlogs.shutdown(timeout_millis=5000)
        journal.save('telemetry_status.json',{'export_key_present':bool(key),'flush_returned':bool(f),
             'shutdown_returned':bool(s),'cloud_delivery_confirmed':False})


def main() -> int:
    ap=argparse.ArgumentParser()
    choice=ap.add_mutually_exclusive_group(required=True)
    choice.add_argument('--incident-seed',type=int)
    choice.add_argument('--source-file',type=Path,help='A new pure adapter source, not restricted to the fault-template bank')
    ap.add_argument('--incoming-file',type=Path,help='Explicit proposed source patch to challenge; not trusted')
    a=ap.parse_args()
    source=None
    incoming=None
    if a.incoming_file is not None:
        if a.incoming_file.stat().st_size>24000:ap.error('Incoming source exceeds byte limit')
        incoming=a.incoming_file.read_text()
    if a.source_file is not None:
        if a.source_file.stat().st_size>24000:ap.error('Source file exceeds byte limit')
        source=a.source_file.read_text()
    r=run(a.incident_seed if a.incident_seed is not None else 0,source_text=source,incoming_source=incoming)
    print(canonical({'run_id':r['run_id'],'status':r['status']}))
    return 0 if r['status']=='VALIDATED_SOURCE_PATCH' else 2

if __name__=='__main__':raise SystemExit(main())
